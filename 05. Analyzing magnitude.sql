-- Comparing the measure values by categories. Understanding data distribution across categories.

-- Finding total customers by countries
SELECT
country,
COUNT(customer_key) AS total_customers
FROM project.customers
GROUP BY country
ORDER BY total_customers DESC

-- Finding total customers by gender
SELECT
gender,
COUNT(customer_key) AS total_customers
FROM project.customers
GROUP BY gender
ORDER BY total_customers DESC

-- Finding total products by category
SELECT
category,
COUNT(product_key) AS total_products
FROM project.products
GROUP BY category
ORDER BY total_products DESC

-- Finding the average costs in each category
SELECT
category,
AVG(cost) AS avg_cost
FROM project.products
GROUP BY category
ORDER BY avg_cost DESC

-- Finding the total revenue generated for each category
SELECT
p.category,
SUM(s.sales_amount) AS total_revenue
FROM project.fact_sales AS s
LEFT JOIN project.products as p
ON s.product_key = p.product_key
GROUP BY category
ORDER BY total_revenue DESC

-- Finding the total revenue generated by each customer
SELECT
c.customer_key,
c.first_name,
c.last_name,
SUM(s.sales_amount) AS total_revenue
FROM project.fact_sales AS s
LEFT JOIN
project.customers AS c
ON s.customer_key = c.customer_key
GROUP BY c.customer_key, c.first_name, c.last_name
ORDER BY total_revenue DESC

-- Finding the distribution of sold items across countries
SELECT
c.country,
SUM(s.quantity) AS total_sold_items
FROM project.fact_sales AS s
LEFT JOIN
project.customers AS c
ON s.customer_key = c.customer_key
GROUP BY c.country
ORDER BY total_sold_items DESC
